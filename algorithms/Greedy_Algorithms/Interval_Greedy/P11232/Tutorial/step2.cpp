//   ✅ 实现了"建模层"：用 O(nm) 暴力扫描，为每辆车产出区间 [l, r]（IR）
//   ✅ 实现了"第一问"：caught = 非空区间个数
//   ✅ 用 DEBUG_IR 开关把 IR 打到 stderr，与样例手算表逐行核对
//   ✅ 用"连续性自检"实证 Step 4 的关键引理（超速下标一定连续）
//   ⬜ 第二问仍未实现（输出占位 0）
//
// 【本步预计得分】0 分
//   ★ 重要认知：本题两问在**同一行**输出，一个测试点要求整行完全正确。
//     第一问对、第二问错 ⟹ 该测试点 0 分。
//     所以本步单独提交拿不到分，它的真正价值是：
//       (a) 验证"建模层"正确 —— 后面所有步骤都建立在这层之上；
//       (b) 作为**对拍基准**（step6.cpp 会用本步的暴力 IR 校验二分 IR）。
//     这正是 step.md「Step 3 部分分实施顺序」的第一环：先把 IR 做对。
//
// 【复杂度】O(nm) —— n,m=10^5 时约 10^10，必然 TLE；n,m≤3000 时约 9×10^6，可过。
//
// 【本步遗留 TODO】
//   TODO: 第二问（区间最小点覆盖）                     → step3.cpp / step4.cpp
//   TODO: 把建模层从 O(nm) 降到 O(n log m)             → step5.cpp
