#include <bits/stdc++.h>
using namespace std;

struct Car {
    int d, v, a;
};

// IR（中间表示）：一辆车 ↔ 一段能拍到它超速的测速仪下标区间。
// 这是本题唯一的中间数据结构：第一问 = 它的聚合，第二问 = 它上面的最优化。
struct Interval {
    int l, r;
};

// 调试开关：1 = 把 IR 与自检信息打到 stderr。
// 用 cerr 而不是 cout —— 评测只比对 stdout，忘记关也不会 WA。
#define DEBUG_IR 0

int main() {
    // TODO: 最终交付版取消注释（见 step7.cpp）
    // freopen("detect.in", "r", stdin);
    // freopen("detect.out", "w", stdout);

    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int T;
    cin >> T;

    while (T--) {
        int n, m, L, V;
        cin >> n >> m >> L >> V;
        (void)L;  // L 用不到：a<0 时超过停车点的测速仪代入公式得负的 v²，自然不超速

        vector<Car> cars(n);
        for (int i = 0; i < n; i++) {
            cin >> cars[i].d >> cars[i].v >> cars[i].a;
        }

        vector<int> p(m + 1);  // 下标 1..m，0 与 m+1 作哨兵
        for (int j = 1; j <= m; j++) {
            cin >> p[j];
        }

        // V² 与每辆车无关，先算好（注意 1LL 防溢出）
        const long long V2 = 1LL * V * V;

        vector<Interval> intervals;
        intervals.reserve(n);  // 最多 n 个区间，一次性预留，避免反复扩容

        // =====================================================================
        // 【建模层】把每辆车压缩成 IR
        // =====================================================================
        for (int i = 0; i < n; i++) {
            int d = cars[i].d;
            int v = cars[i].v;
            int a = cars[i].a;

            // ---- (1) 定位轴上的起点 ----
            // 车从 d 驶入并向北行驶，只有 p_j >= d 的测速仪才可能拍到它。
            // 用 >= 而不是 > ，因为题面明确"驶入时若该位置有测速仪也要测速"。
            // lower_bound 返回第一个不小于 d 的下标；若全部 p_j < d 则返回 m+1。
            int start = lower_bound(p.begin() + 1, p.end(), d) - p.begin();

            if (start == m + 1) {
                // 所有测速仪都在出发点南边 ⟹ 这辆车永远不会被拍 ⟹ 空 IR
                if (DEBUG_IR) cerr << "car " << i << ": 无测速仪可达，空区间\n";
                continue;
            }

            // ---- (2) 暴力扫描：直接数出第一个 / 最后一个超速的测速仪 ----
            // 判定谓词（step1 形式化的产物）：
            //     over(j) ⟺ v² + 2a(p_j - d) > V²
            // 全程整数，无开方、无浮点。
            int l = -1, r = -1, cnt = 0;
            for (int j = start; j <= m; j++) {
                long long speed2 = 1LL * v * v + 2LL * a * (p[j] - d);
                if (speed2 > V2) {           // ★ 严格大于："超过"限速
                    if (l == -1) l = j;      // 第一次命中 ⟹ 左端点
                    r = j;                   // 每次都更新 ⟹ 结束时是右端点
                    cnt++;
                }
            }

            if (l == -1) {
                // 一个都没拍到 ⟹ 空 IR ⟹ 第一问不计数
                if (DEBUG_IR) cerr << "car " << i << ": 全程不超速，空区间\n";
                continue;
            }

            // ---- (3) 实证 Step 4 的关键引理 ----
            // 【引理】v²(p) = v² + 2a(p-d) 是关于 p 的一次函数：
            //         a>0 严格递增、a=0 常数、a<0 严格递减。
            //         ⟹ over(i,·) 在 j = start..m 上的真假序列必为
            //            F…F T…T / T…T F…F / 全 T / 全 F
            //         ⟹ 命中的下标一定**连续**，即 cnt == r - l + 1。
            // 这个自检是"用数据验证猜想"：一旦某组数据打破连续性，
            // 后面的二分（step5）和区间贪心（step4）就都不成立了。
            if (DEBUG_IR) {
                cerr << "car " << i << " (d=" << d << ",v=" << v << ",a=" << a
                     << ") -> [" << l << "," << r << "]  cnt=" << cnt;
                if (cnt != r - l + 1) cerr << "   !!! 连续性被破坏 !!!";
                cerr << '\n';
            }

            intervals.push_back({l, r});
        }

        // =====================================================================
        // 【第一问】全开时被判超速的车辆数 = 非空 IR 的个数
        //   为什么？一辆车被判超速 ⟺ 至少有一个开启的测速仪拍到它超速
        //            ⟺ 它的 IR 非空。
        // =====================================================================
        int caught = static_cast<int>(intervals.size());

        if (DEBUG_IR) {
            cerr << "caught = " << caught << "，区间列表：";
            for (const Interval& s : intervals) cerr << "[" << s.l << "," << s.r << "] ";
            cerr << '\n';
        }

        // =====================================================================
        // TODO: 【第二问】求最小保留集合 S，使每个非空区间都含 S 中至少一个下标，
        //       答案 = m - |S|。
        //       本步先输出占位值 0（即"一个都不关"，合法但绝非最优）。
        //       → step3.cpp 用 2^m 子集枚举解决 m ≤ 20 的情况（拿测试点 1、2）
        //       → step4.cpp 归约为区间最小点覆盖 + 右端点贪心（正解）
        // =====================================================================
        int closed = 0;

        cout << caught << ' ' << closed << '\n';
    }

    return 0;
}
