struct Car {
    int d, v, a;
};

int main() {
    // 正式比赛必须使用文件读写，文件名 = 题目英文名（本题 detect）。
    // 文件名错一个字母 = 0 分。本地调试时可先用标准输入输出。
    // TODO: 最终交付版取消注释（见 step7.cpp）
    // freopen("detect.in", "r", stdin);
    // freopen("detect.out", "w", stdout);

    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    // =========================================================================
    // 【Step 1.1 关键词圈注表】—— 漏掉任何一条就是一个测试点
    // -------------------------------------------------------------------------
    //  ① "瞬时速度 **超过** 限速 V"
    //       → 严格大于：v_now > V，等价于 v_now² > V²。不能写 >=。
    //       → 样例第一辆车 v = V = 3，明确"没有超速"，就是专门卡这一条。
    //  ② "a_i 可正可负，也可以为零"
    //       → 分类讨论信号。对应特殊性质 A(a=0) / B(a>0) / C(a<0)。
    //  ③ "当车辆行驶到最北端 **或速度降为 0** 时驶离主干道"
    //       → a<0 的车可能在到达 L 之前就走了，后面的测速仪拍不到它。
    //  ④ "车辆 **驶入与驶出** 时，如果对应位置有测速仪，也会测速"
    //       → 端点包含性：位置恰好等于 d 的测速仪要算（用 >= d，不是 > d）；
    //         位置恰好等于 L 的测速仪也要算。
    //  ⑤ "第一行包含一个正整数 T，表示数据组数"
    //       → 多组数据，所有容器每组都要重建（本文件用局部变量，天然清空）。
    //  ⑥ "如果你使用浮点数进行计算，需要注意潜在的精度问题"
    //       → 出题人明示：禁止开平方、禁止 double。全程用整数比较平方。
    // =========================================================================

    // =========================================================================
    // 【Step 1.2 形式化：写出判定谓词】
    // -------------------------------------------------------------------------
    //  由提示公式  v_s² = v0² + 2·a·s ，其中 s = p_j - d_i 是行驶距离：
    //
    //      over(i, j)  ⟺  v_i² + 2·a_i·(p_j - d_i)  >  V²
    //
    //  这个谓词就是整道题的"原子"。后面所有算法都只是在高效地回答：
    //      "对固定的 i，哪些 j 使 over(i,j) 成立？"
    //
    //  量级估算（决定用什么类型）：
    //      |2·a·(p-d)| ≤ 2 × 1000 × 10^6 = 2×10^9   ← 已经超过 int 的安全区
    //      v² ≤ 10^6 ,  V² ≤ 10^6
    //  结论：所有乘法必须写成 1LL * ... 提升为 long long。
    // =========================================================================

    // =========================================================================
    // 【Step 2 复杂度预算】
    // -------------------------------------------------------------------------
    //  n, m ≤ 10^5，T ≤ 20，时限通常 1s 级别
    //    → 总预算约 O(n log n)
    //    → "每辆车扫一遍所有测速仪" = O(nm) = 10^10，直接出局
    //    → 每辆车最多只能花 O(log m)
    //    → 必须二分；二分的前提是"单调"
    //    → 于是 Step 4 的任务变成：证明 over(i, ·) 关于 j 单调。
    //  这就是"数据范围反推算法"的完整链条。
    // =========================================================================

    // =========================================================================
    // 【Step 3 子任务逆向工程】
    // -------------------------------------------------------------------------
    //  测试点 1、2  ：n,m ≤ 10 / 20      → 暴力即可（含第二问 2^m 枚举）
    //  测试点 3、4  ：特殊性质 A（a = 0）→ 速度恒定，只判 v > V
    //  测试点 5、6  ：特殊性质 B（a > 0）→ 速度递增 ⟹ 超速区间是"后缀"
    //  测试点 7、8  ：特殊性质 C（a < 0）→ 速度递减 ⟹ 超速区间是"前缀"
    //  测试点 9、10 ：无特殊性质          → 三个分支合一
    //  ★ 结论：特殊性质 A/B/C 的并集 = 按 a 的符号分类讨论 = 正解框架。
    // =========================================================================

    // =========================================================================
    // 【Step 1.3 手玩样例】L=15, V=3, V²=9, p = [_, 2, 5, 8, 9, 15]（下标 1..5）
    // -------------------------------------------------------------------------
    //  车1 (0,3,0)  : a=0 且 v=3 不 > 3            → 无区间
    //  车2 (12,4,0) : start = 第一个 p≥12 → 下标5   → a=0 且 4>3 → [5,5]
    //  车3 (1,1,4)  : start=1；1+8(p-1)>9 ⟺ p>2    → 首个是 p=5(下标2) → [2,5]
    //  车4 (5,5,-2) : start=2；25-4(p-5)>9 ⟺ p<9   → 末个是 p=8(下标3) → [2,3]
    //  车5 (6,4,-4) : start=3；16-8(8-6)=0 ≤ 9     → 无区间（区间内没有测速仪）
    //
    //  第一问 = 非空区间个数 = 3                       ✔ 与样例解释一致
    //  第二问：区间集 {[5,5], [2,5], [2,3]}
    //          按右端点排序 → [2,3], [5,5], [2,5]
    //          selected=0 <2 → 选 3，keep=1
    //          selected=3 <5 → 选 5，keep=2
    //          [2,5]：selected=5 ≥ 2 → 已覆盖
    //          keep=2 → 可关闭 5-2 = 3                  ✔ 输出 "3 3"
    //
    //  ★ 从手玩中直接读出两个建模结论：
    //     (a) 每辆车对应"一段连续的测速仪下标区间"；
    //     (b) 第二问 = 用最少的点命中所有区间（区间最小点覆盖）。
    // =========================================================================

    // =========================================================================
    // 【观察 3】本题其实用不到 L！
    // -------------------------------------------------------------------------
    //  L 只在"车是否在北端驶出"时才有意义。但：
    //    · a ≥ 0：车一定能到达 L，所有 p_j ≥ d 的测速仪都能拍到；
    //    · a < 0：若车在中途速度降为 0，则它之后的测速仪代入公式会得到
    //             v² = v0² + 2a·s < 0 ≤ V²，自然判为"不超速"。
    //  也就是说"中途驶离"这件事被公式自动处理了，不需要显式求停车位置。
    //  这是"用 v² 比较"而不是"用 sqrt 计算"带来的额外好处。
    // =========================================================================

    int T;
    cin >> T;

    while (T--) {
        int n, m, L, V;
        cin >> n >> m >> L >> V;
        (void)L;  // 见【观察 3】，L 在本题中不参与计算

        vector<Car> cars(n);
        for (int i = 0; i < n; i++) {
            cin >> cars[i].d >> cars[i].v >> cars[i].a;
        }

        // 测速仪下标使用 1..m：
        //   · 0    作为"尚未选点"的哨兵；
        //   · m+1  作为"找不到"的哨兵。
        // 有了哨兵，几乎所有边界特判都会消失。
        vector<int> p(m + 1);
        for (int j = 1; j <= m; j++) {
            cin >> p[j];
        }

        // ---------------------------------------------------------------------
        // TODO: 【建模层】对每辆车 i，求出测速仪下标区间 [l_i, r_i]
        //       l_i = 第一个使 over(i,j) 成立的 j
        //       r_i = 最后一个使 over(i,j) 成立的 j
        //       若不存在则为"空区间"，该车不计入第一问。
        //       → 由 step2.cpp 用 O(nm) 暴力实现（同时作为对拍基准）
        //       → 由 step5.cpp 用 O(n log m) 定向二分实现（正解）
        // ---------------------------------------------------------------------

        // ---------------------------------------------------------------------
        // TODO: 【第一问】caught = 非空区间的个数
        //       → 由 step2.cpp 完成
        // ---------------------------------------------------------------------

        // ---------------------------------------------------------------------
        // TODO: 【第二问】保留集合 S 必须命中每个非空区间，求 m - min|S|
        //       → 由 step3.cpp 用 2^m 子集枚举完成（m ≤ 20）
        //       → 由 step4.cpp 用区间最小点覆盖贪心完成（正解）
        // ---------------------------------------------------------------------

        int caught = 0;   // 占位
        int closed = 0;   // 占位

        cout << caught << ' ' << closed << '\n';
    }

    return 0;
}
