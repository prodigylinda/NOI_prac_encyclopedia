#include <bits/stdc++.h>
using namespace std;

struct Car {
    int d, v, a;
};

// IR：一辆车 ↔ 一段能拍到它超速的测速仪下标区间
struct Interval {
    int l, r;
};

struct TestCase {
    int n = 0, m = 0, L = 0, V = 0;
    vector<Car> cars;
    vector<int> p;   // 下标 1..m
};

#define DEBUG_IR 0   // 审计项 □10：调试信息走 cerr 且默认关闭

// =============================================================================
// 二分原语：只依赖单调性，不含任何题意
// =============================================================================

// [lo,hi] 上第一个使 pred 为真的下标；pred 形如 F…F T…T；全假返回 hi+1
template <class Pred>
int first_true(int lo, int hi, Pred pred) {
    int ans = hi + 1;
    while (lo <= hi) {
        int mid = lo + (hi - lo) / 2;
        if (pred(mid)) { ans = mid; hi = mid - 1; }
        else           { lo = mid + 1; }
    }
    return ans;
}

// [lo,hi] 上最后一个使 pred 为真的下标；pred 形如 T…T F…F；全假返回 lo-1
template <class Pred>
int last_true(int lo, int hi, Pred pred) {
    int ans = lo - 1;
    while (lo <= hi) {
        int mid = lo + (hi - lo) / 2;
        if (pred(mid)) { ans = mid; lo = mid + 1; }
        else           { hi = mid - 1; }
    }
    return ans;
}

// =============================================================================
// ① I/O 层
// =============================================================================
TestCase readCase() {
    TestCase tc;
    cin >> tc.n >> tc.m >> tc.L >> tc.V;

    tc.cars.resize(tc.n);
    for (int i = 0; i < tc.n; i++) {
        cin >> tc.cars[i].d >> tc.cars[i].v >> tc.cars[i].a;
    }

    tc.p.assign(tc.m + 1, 0);
    for (int j = 1; j <= tc.m; j++) {
        cin >> tc.p[j];
    }
    return tc;
}

// =============================================================================
// ② 建模层：原始输入 → IR。本题唯一含"题意"的一层。
//    依据【引理】f(j) = v² + 2a(p_j - d) 关于 j 单调（斜率 2a）：
//      a ≥ 0 ⟹ over 形如 F…F T…T（或常函数）⟹ 命中集是后缀 [l, m]
//      a < 0 ⟹ over 形如 T…T F…F            ⟹ 命中集是前缀 [start, r]
// =============================================================================
vector<Interval> buildIR(const TestCase& tc) {
    const long long V2 = 1LL * tc.V * tc.V;   // 审计项 □3
    vector<Interval> ir;
    ir.reserve(tc.n);                          // 审计项 □5：一次分配，避免反复扩容

    for (int i = 0; i < tc.n; i++) {
        const int d = tc.cars[i].d;
        const int v = tc.cars[i].v;
        const int a = tc.cars[i].a;

        // 轴上的起点：第一个 p_j >= d（审计项 □4：端点包含，用 >=）
        int start = lower_bound(tc.p.begin() + 1, tc.p.end(), d) - tc.p.begin();
        if (start == tc.m + 1) continue;       // 边界情形 ⑤：空 IR

        // 判定谓词：整数比较平方，无开方无浮点（审计项 □3、□4）
        auto over = [&](int j) -> bool {
            return 1LL * v * v + 2LL * a * (tc.p[j] - d) > V2;
        };

        int l, r;
        if (a >= 0) {
            // 单调不减 ⟹ 后缀。a==0 的全真/全假被 first_true 自动涵盖。
            l = first_true(start, tc.m, over);
            if (l > tc.m) continue;            // 边界情形 ⑥：全程不超速 ⟹ 空 IR
            r = tc.m;
        } else {
            // 单调不增 ⟹ 前缀。先验第一个可拍点，否则后面只会更慢。
            if (!over(start)) continue;        // 边界情形 ④⑥：空 IR
            l = start;
            r = last_true(start, tc.m, over);  // 停车点之后 speed2<0，自动排除
        }

        if (DEBUG_IR) {
            cerr << "car " << i << " (d=" << d << ",v=" << v << ",a=" << a
                 << ") -> [" << l << "," << r << "]\n";
        }
        ir.push_back({l, r});
    }
    return ir;
}

// =============================================================================
// ③ 算法层：区间最小点覆盖（与题意无关，可跨题复用）
//    贪心：按右端点升序，未被命中就选当前区间的右端点。
//    正确性（交换论证）：设最优解 O，对排序后首个区间 I₁=[l₁,r₁]，
//    O 必含某 x ≤ r₁；把 x 换成 r₁ 后，任何含 x 的区间 [l,r] 满足
//    l ≤ x ≤ r₁ ≤ r（排序保证 r ≥ r₁），故仍含 r₁ ⟹ 替换后合法且 |O| 不变。
//    归纳得 |贪心| ≤ |O|。∎
// =============================================================================
int minStab(vector<Interval> segs) {   // 按值传参：内部排序不污染调用方的 IR
    if (segs.empty()) return 0;        // 边界情形 ⑦

    sort(segs.begin(), segs.end(),
         [](const Interval& x, const Interval& y) {
             return x.r < y.r;         // 审计项：必须严格 <，否则破坏严格弱序 → RE
         });

    int keep = 0;
    int selected = 0;                  // 哨兵 0 = 尚未选点（下标从 1 开始）
    for (const Interval& s : segs) {
        if (selected < s.l) {          // 未被命中
            selected = s.r;
            keep++;
        }
    }
    return keep;
}

